""" 
1- Operadores Aritméticos: Son los operadores que se utilizan para realizar operaciones matemáticas básicas como suma, resta, multiplicación, división, módulo, potencia y división entera.
Los operadores aritméticos en Python son: 
+ (suma),
 - (resta),
* (multiplicación),
 / (división),
 % (módulo),
** (potencia) 
y // (división entera).
2- Operadores de Comparación: Son los operadores que se utilizan para comparar dos valores y devolver un valor booleano (True o False) según el resultado de la comparación.
Los operadores de comparación en Python son:
== (igual),
!= (no igual),
> (mayor que),
< (menor que),
>= (mayor o igual que),
<= (menor o igual que).
3- Operadores de Asignación: Son los operadores que se utilizan para asignar valores a variables.
Los operadores de asignación en Python son:
= (igual),
+= (suma y asignación),
-= (resta y asignación),
*= (multiplicación y asignación),
/= (división y asignación),
%= (módulo y asignación),
**= (potencia y asignación),
y //= (división entera y asignación).
4- Operadores de Incremento y Decremento: Son los operadores que se utilizan para incrementar y decrementar valores de variables.
Los operadores de incremento y decremento en Python son:
+= (incremento),
-= (decremento).
4- Operadores Lógicos: Son los operadores que se utilizan para combinar expresiones booleanas y devolver un valor booleano según el resultado de la combinación.
Los operadores lógicos en Python son:
and (y),
or (o),
not (no).
"""
# Puede multiplicar un string por un número entero para repetirlo esa cantidad de veces
print("Hola" * 3)  # Imprime "HolaHolaHola" en la consola, ya que el string "Hola" se repite 3 veces

# Si comparamos cadenas de texto con operadores de comparación, se comparan los valores ASCII de los caracteres.
print("a" > "b")  # Imprime False, ya que el valor ASCII de "a" es menor que el valor ASCII de "b"

# Si comparamos cadenas de texto con operadores de comparación, se comparan los valores ASCII de los caracteres.
print("a" == "a")  # Imprime True, ya que los valores ASCII de "a" y "a" son iguales 


