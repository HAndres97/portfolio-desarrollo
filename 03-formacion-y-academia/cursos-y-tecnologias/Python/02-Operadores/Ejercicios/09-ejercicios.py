""" 
Aplica el operador not para invertir el resultado de la comparación 15 > 20. ¿Cuál es el resultado? 

"""
print(not (15 > 20)) # Comparamos si 15 es mayor que 20 y luego aplicamos el operador lógico not para invertir el resultado. El resultado es True porque la comparación original es False y al aplicar not se invierte a True.  