""" 
Usa el operador or para verificar si el número 7 es menor que 3 o mayor que 5.
Imprime el resultado. 
"""
print(7 < 3 or 7 > 5) # Comparamos si 7 es menor que 3 o mayor que 5 usando el operador lógico or y lo imprimimos en la consola. El resultado es True porque al menos una de las condiciones es verdadera.