""" 
Compara dos cadenas de texto (“apple” y “banana”) usando los operadores > y < y explica cuál tiene mayor orden alfabético.
"""

print("apple" > "banana") # Comparamos si "apple" es mayor que "banana" y lo imprimimos en la consola. El resultado es False porque "apple" tiene menor orden alfabético que "banana".
print("apple" < "banana") # Comparamos si "apple" es menor que "banana" y lo imprimimos en la consola. El resultado es True porque "apple" tiene menor orden alfabético que "banana".
