"""
Convierte el número 7 en una cadena de texto y concaténalo con la frase “ es mi número favorito”. 
Imprime el resultado.  
"""
numero_favorito = 7  # Declaramos la variable numero_favorito con el valor 7
numero_favorito_str = str(numero_favorito)  # Convertimos el número 7 en una cadena de texto
resultado = numero_favorito_str + " es mi número favorito"  # Concatenamos la cadena de texto con la frase
print(resultado)  # Imprimimos el resultado en la consola