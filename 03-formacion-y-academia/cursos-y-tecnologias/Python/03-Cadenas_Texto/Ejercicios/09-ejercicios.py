""" 
Cuenta cuántas veces aparece la letra "n" en la cadena "Python es un lenguaje de programación" y muestra el resultado.
"""
cadena = "Python es un lenguaje de programación"  # Declaramos la variable cadena con la cadena "Python es un lenguaje de programación"
cantidad_n = cadena.count("n")
print(cantidad_n)  # Imprimimos la cantidad de veces que aparece la letra "n" en la cadena