""" 
Extrae un “slice” de la palabra “Programación” para obtener los caracteres desde la posición 3 hasta la 7. 
"""
palabra = "Programación"  # Declaramos la variable palabra con la cadena "Programación"
slice_palabra = palabra[3:7]  # Extraemos un slice de la palabra desde la posición 3 hasta la 7 (el índice 7 se incluye)
print(slice_palabra)  # Imprimimos el resultado del slice, que será "gram"