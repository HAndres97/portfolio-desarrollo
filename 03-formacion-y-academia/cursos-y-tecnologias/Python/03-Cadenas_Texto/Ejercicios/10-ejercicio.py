"""
Verifica si la cadena “12345” es numérica usando el método adecuado e imprime el resultado. 
"""
cadena = "12345"  # Declaramos la variable cadena con la cadena "12345"
es_numerica = cadena.isnumeric()  # Verificamos si la cadena es numérica usando el método isnumeric()
print(es_numerica)  # Imprimimos el resultado de la verificación, que será True si la cadena es numérica y False en caso contrario