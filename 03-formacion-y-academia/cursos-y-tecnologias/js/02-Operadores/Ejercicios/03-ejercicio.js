/*
Imprime 5 comparaciones verdaderas con diferentes operadores de comparación. 
*/

console.log(10 == 10); // true
console.log(10 != 10); // false
console.log(10 > 10); // false
console.log(10 < 10); // false
console.log(10 >= 10); // true
console.log(10 <= 10); // true
console.log("10" == 10); // true
console.log("10" === 10); // false
console.log("10" !== 10); // true
console.log("10" != 10); // false
